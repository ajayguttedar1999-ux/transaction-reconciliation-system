-- 2. Fact Table: Historical Transactions (Billions of rows partitioned by Trade Date)
CREATE OR REPLACE TABLE FACT_TRANSACTIONS (
    TRANSACTION_KEY INT AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    TRANSACTION_ID VARCHAR(100) NOT NULL UNIQUE,
    PRODUCT_KEY INT REFERENCES DIM_PRODUCT(PRODUCT_KEY),
    PRODUCT_ID VARCHAR(50) NOT NULL,
    TRANSACTION_TYPE VARCHAR(20) NOT NULL, -- BUY, SELL
    QUANTITY NUMBER(18, 4) NOT NULL,
    PRICE NUMBER(18, 4) NOT NULL,
    TOTAL_AMOUNT NUMBER(18, 4) NOT NULL,
    TRADE_DATE DATE NOT NULL,
    SETTLEMENT_DATE DATE,
    STATUS VARCHAR(20) NOT NULL, -- BOOKED, SETTLED, CANCELLED
    SOURCE_SYSTEM VARCHAR(50) DEFAULT 'RECON_PLATFORM',
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
CLUSTER BY (TRADE_DATE, PRODUCT_ID); -- Snowflake Automatic Clustering for optimal pruning

-- 3. Fact Table: Position Snapshots (Daily In-Memory / DB capture)
CREATE OR REPLACE TABLE FACT_POSITION_SNAPSHOTS (
    SNAPSHOT_KEY INT AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    POSITION_ID VARCHAR(100) NOT NULL,
    PRODUCT_KEY INT REFERENCES DIM_PRODUCT(PRODUCT_KEY),
    PRODUCT_ID VARCHAR(50) NOT NULL,
    TOTAL_QUANTITY NUMBER(18, 4) NOT NULL,
    TOTAL_AMOUNT NUMBER(18, 4) NOT NULL,
    POSITION_VERSION INT NOT NULL,
    SNAPSHOT_DATE DATE NOT NULL,
    CAPTURED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
CLUSTER BY (SNAPSHOT_DATE, PRODUCT_ID);

-- 4. Fact Table: Reconciliation Balance Runs (The Primary Audit Ledger)
CREATE OR REPLACE TABLE FACT_RECON_BALANCE_RUNS (
    RECON_RUN_KEY INT AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    RUN_ID VARCHAR(100) NOT NULL,
    RECON_DATE DATE NOT NULL,
    PRODUCT_ID VARCHAR(50) NOT NULL,
    TRANSACTION_TOTAL_QTY NUMBER(18, 4) NOT NULL,
    POSITION_TOTAL_QTY NUMBER(18, 4) NOT NULL,
    DISCREPANCY_QTY NUMBER(18, 4) NOT NULL,
    STATUS VARCHAR(20) NOT NULL, -- BALANCED, IMBALANCED
    IS_STALE BOOLEAN DEFAULT FALSE,
    STALE_REASON VARCHAR(255),
    EXECUTED_AT TIMESTAMP_NTZ NOT NULL,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
CLUSTER BY (RECON_DATE, STATUS);
